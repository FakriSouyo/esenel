/**
 * Generates supabase/migrations/0002_seed.sql from the static data
 * modules (data/products.js, data/collections.js, data/journal.js,
 * data/flowers.js). Run with:
 *
 *   node scripts/generate-supabase-seed.mjs
 *
 * The data modules are plain ESM with no imports, so they are loaded
 * via data: URLs to sidestep the CommonJS default of .js files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

// Map a local asset path to its Supabase Storage public URL (mirrors
// lib/supabase.js storageUrl). Shared by the value mapping below AND
// injected into the loaded data modules (they now import '@/lib/supabase',
// which a data: URL can't resolve).
const storageUrl = (path) => {
  if (!path || typeof path !== 'string') return path;
  if (path.startsWith('/katalog_esenel/')) {
    const key = path.slice('/katalog_esenel/'.length).split('/').map(encodeURIComponent).join('/');
    return `${process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://jimsgyrsgygicxwyuqzo.supabase.co'}/storage/v1/object/public/katalog/${key}`;
  }
  if (path.startsWith('/flowers/')) {
    const key = path.slice('/flowers/'.length).split('/').map(encodeURIComponent).join('/');
    return `${process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://jimsgyrsgygicxwyuqzo.supabase.co'}/storage/v1/object/public/craft/${key}`;
  }
  return path;
};

async function load(name) {
  let code = readFileSync(`${ROOT}data/${name}.js`, 'utf8');
  // The data modules import storageUrl from '@/lib/supabase' — swap that
  // for an inline copy so they can be loaded as standalone ESM.
  code = code.replace(
    /import \{ storageUrl \} from ['"]@\/lib\/supabase['"];?\s*/,
    ''
  );
  code = `const storageUrl = (${storageUrl.toString()});\n${code}`;
  const mod = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
  return mod;
}

const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sqlArr = (arr) => `ARRAY[${arr.map(sql).join(', ')}]`;
const sqlBool = (b) => (b ? 'true' : 'false');
const sqlDate = (s) => {
  const d = new Date(s);
  if (Number.isNaN(d.getTime())) return 'NULL';
  return `'${d.toISOString().slice(0, 10)}'`;
};

// (storageUrl is defined above; journal covers are external — untouched.)

const lines = [];
lines.push('-- ============================================================');
lines.push('-- ESENEL — seed data (generated by scripts/generate-supabase-seed.mjs)');
lines.push('-- ============================================================');
lines.push('');

const productsMod = await load('products');
const collectionsMod = await load('collections');
const journalMod = await load('journal');
const flowersMod = await load('flowers');

// ---- categories ----------------------------------------------------
lines.push('insert into public.categories (slug, label, subtitle, image, "order") values');
productsMod.categories.forEach((cat, i) => {
  const copy = collectionsMod.collectionCopy[cat.slug];
  const img = collectionsMod.collectionImages[cat.slug] || null;
  lines.push(
    `  (${sql(cat.slug)}, ${sql(cat.label)}, ${sql(copy?.tagline || '')}, ${
      img ? sql(storageUrl(img)) : 'NULL'
    }, ${i})${i === productsMod.categories.length - 1 ? ';' : ','}`
  );
});
lines.push('');

// ---- products ------------------------------------------------------
lines.push('insert into public.products');
lines.push('  (slug, name, category_slug, subtitle, price, image, gallery, composition, description, featured, is_new, best_seller)');
lines.push('values');
productsMod.products.forEach((p, i) => {
  const last = i === productsMod.products.length - 1;
  lines.push(
    `  (${sql(p.slug)}, ${sql(p.name)}, ${sql(p.category)}, ${sql(p.subtitle)}, ${p.price}, ` +
      `${sql(storageUrl(p.image))}, ${sqlArr(p.gallery.map(storageUrl))}, ${sqlArr(p.composition)}, ${sql(p.description)}, ` +
      `${sqlBool(p.featured)}, ${sqlBool(p.isNew)}, ${sqlBool(p.bestSeller)})${last ? ';' : ','}`
  );
});
lines.push('');

// ---- journal -------------------------------------------------------
if (journalMod.posts.length) {
  lines.push('insert into public.journal_posts');
  lines.push('  (slug, title, category, published_on, read_time, image, excerpt, featured, body)');
  lines.push('values');
  journalMod.posts.forEach((post, i) => {
    const last = i === journalMod.posts.length - 1;
    lines.push(
      `  (${sql(post.slug)}, ${sql(post.title)}, ${sql(post.category)}, ${sqlDate(post.date)}, ` +
        `${sql(post.readTime)}, ${sql(post.image)}, ${sql(post.excerpt)}, ${sqlBool(post.featured)}, ` +
        `${sqlArr(post.body)})${last ? ';' : ','}`
    );
  });
  lines.push('');
}

// ---- craft ---------------------------------------------------------
lines.push('insert into public.craft_sizes (id, label, base_price, stem_count, "order") values');
flowersMod.craftSizes.forEach((s, i) => {
  lines.push(
    `  (${sql(s.id)}, ${sql(s.label)}, ${s.basePrice}, ${s.stemCount}, ${i})${
      i === flowersMod.craftSizes.length - 1 ? ';' : ','
    }`
  );
});
lines.push('');

lines.push('insert into public.craft_flowers (id, name, price_per_stem, image, "order") values');
flowersMod.craftFlowers.forEach((f, i) => {
  lines.push(
    `  (${sql(f.id)}, ${sql(f.name)}, ${f.pricePerStem}, ${sql(f.image)}, ${i})${
      i === flowersMod.craftFlowers.length - 1 ? ';' : ','
    }`
  );
});
lines.push('');

lines.push('insert into public.craft_wrappings (id, name, hex, "order") values');
flowersMod.craftWrappings.forEach((w, i) => {
  lines.push(
    `  (${sql(w.id)}, ${sql(w.name)}, ${sql(w.hex)}, ${i})${
      i === flowersMod.craftWrappings.length - 1 ? ';' : ','
    }`
  );
});
lines.push('');

// ---- reset identity sequences so future ids continue cleanly --------
lines.push('select setval(pg_get_serial_sequence(\'public.products\', \'id\'), (select max(id) from public.products));');
lines.push('select setval(pg_get_serial_sequence(\'public.journal_posts\', \'id\'), (select max(id) from public.journal_posts));');
lines.push('');

const out = lines.join('\n');
writeFileSync(`${ROOT}supabase/migrations/0002_seed.sql`, out, 'utf8');
console.log(`Wrote supabase/migrations/0002_seed.sql (${out.length} bytes, ${productsMod.products.length} products, ${journalMod.posts.length} posts)`);
